/*
 * Writes `packages/gutentype-server/lib/font-data.ts`: Open Sans (regular and bold, Latin subset, SIL Open Font
 * License, shipped by Keybr in `keybr-themes/assets`) decoded from WOFF2 to TrueType, so the share card renders text
 * on a server with no system fonts. Run from the repo root:
 *
 *   node --import @keybr/tsl packages/gutentype-tools/lib/server-font-build.ts
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { woff2ToTtf } from "./server-woff2.ts";

const root = join(import.meta.dirname, "..", "..", "..");
const themes = join(root, "packages", "keybr-themes");
const out = join(root, "packages", "gutentype-server", "lib", "font-data.ts");

const fonts = [
  { name: "regular", file: "open-sans-400.latin.woff2" },
  { name: "bold", file: "open-sans-700.latin.woff2" },
];

const lines = [
  "// Generated by packages/gutentype-tools/lib/server-font-build.ts. Do not edit.",
  "// Open Sans, Latin subset, decoded from Keybr's WOFF2 to TrueType. Copyright 2020 The Open Sans Project Authors.",
  "// SIL Open Font License 1.1: packages/keybr-themes/licenses/OpenSans.txt.",
  "",
  `export const fontFamily = "Open Sans";`,
  "",
];
for (const { name, file } of fonts) {
  const ttf = woff2ToTtf(await readFile(join(themes, "assets", file)));
  lines.push(
    `export const ${name}Ttf = ${JSON.stringify(ttf.toString("base64"))};`,
    "",
  );
  console.log(`${file}: ${ttf.length} bytes of TrueType`);
}
await writeFile(out, lines.join("\n"));
console.log(`wrote ${out}`);
