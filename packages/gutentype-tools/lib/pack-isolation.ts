#!/usr/bin/env bun
/**
 * ISC-26 helper, driven by `scripts/pack-isolation-check.sh`: adding a pack touches only the content package.
 *
 *   bun pack-isolation.ts add      writes a dummy Spanish pack into packages/gutentype-content/lib/packs/es and
 *                                  regenerates lib/generated.ts from every pack directory there
 *   bun pack-isolation.ts check    loads the dummy pack through the public @gutentype/content and
 *                                  @gutentype/lesson APIs, exactly as the app would
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { buildPackDir } from "./build-learn.ts";

const contentLib = resolve(
  dirname(new URL(import.meta.url).pathname),
  "../../gutentype-content/lib",
);

/** Juan 1:1-3, Reina-Valera 1909 (public domain): enough text to prove a pack loads, not a Learn corpus. */
const juan = [
  [
    "En el principio era el Verbo, y el Verbo era con Dios, y el Verbo era Dios.",
    "Este era en el principio con Dios.",
    "Todas las cosas por él fueron hechas; y sin él nada de lo que es hecho, fué hecho.",
  ],
];

function addDummyPack() {
  const dir = join(contentLib, "packs", "es");
  mkdirSync(join(dir, "books"), { recursive: true });
  const words = new Map<string, number>();
  const letters = new Map<string, number>();
  for (const verse of juan.flat()) {
    for (const w of verse.toLowerCase().match(/\p{L}+/gu) ?? []) {
      words.set(w, (words.get(w) ?? 0) + 1);
      for (const ch of w) letters.set(ch, (letters.get(ch) ?? 0) + 1);
    }
  }
  writeFileSync(
    join(dir, "books", "juan.json"),
    JSON.stringify({ id: "juan", name: "Juan", chapters: juan }),
  );
  writeFileSync(
    join(dir, "pack.json"),
    JSON.stringify(
      {
        id: "es",
        label: "Reina-Valera 1909 (prueba)",
        short: "RVR",
        language: "es",
        license: "Dominio público.",
        sourceUrl: "https://example.invalid/rvr1909.txt",
        sourceSha256: "0".repeat(64),
        verses: juan.flat().length,
        omitted: [],
        letters: [...letters].sort((a, b) => b[1] - a[1]),
        books: [
          { id: "juan", name: "Juan", chapters: juan.map((c) => c.length) },
        ],
      },
      null,
      1,
    ),
  );
  writeFileSync(
    join(dir, "words.json"),
    JSON.stringify(
      [...words].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)),
    ),
  );
  buildPackDir(dir);
}

/** Writes lib/generated.ts in the shape build-packs.ts gives it, for every pack directory present. */
function writeGenerated() {
  const ids = readdirSync(join(contentLib, "packs")).sort((a, b) =>
    a === "bsb"
      ? -1
      : b === "bsb"
        ? 1
        : a === "kjv"
          ? -1
          : b === "kjv"
            ? 1
            : a < b
              ? -1
              : 1,
  );
  const lines = [
    "// Generated by packages/gutentype-tools/lib/build-packs.ts. Do not edit.",
    ...ids.map(
      (id) =>
        `import ${id} from "./packs/${id}/pack.json" with { type: "json" };`,
    ),
    "",
    "export const packInfos = [" + ids.join(", ") + "];",
    "",
    "export async function importBook(pack: string, book: string): Promise<unknown> {",
    "  switch (`${pack}/${book}`) {",
  ];
  for (const id of ids) {
    const pack = JSON.parse(
      readFileSync(join(contentLib, "packs", id, "pack.json"), "utf8"),
    );
    for (const { id: b } of pack.books as { id: string }[]) {
      lines.push(
        `    case "${id}/${b}":`,
        `      return (await import(/* webpackChunkName: "gt-${id}-${b}" */ "./packs/${id}/books/${b}.json", { with: { type: "json" } })).default;`,
      );
    }
  }
  lines.push(
    "  }",
    "  throw new Error(`unknown book ${pack}/${book}`);",
    "}",
    "",
  );
  for (const [kind, fn] of [
    ["words", "importWords"],
    ["learn", "importLearn"],
  ]) {
    lines.push(
      `export async function ${fn}(pack: string): Promise<unknown> {`,
      "  switch (pack) {",
    );
    for (const id of ids) {
      lines.push(
        `    case "${id}":`,
        `      return (await import(/* webpackChunkName: "gt-${id}-${kind}" */ "./packs/${id}/${kind}.json", { with: { type: "json" } })).default;`,
      );
    }
    lines.push("  }", "  throw new Error(`unknown pack ${pack}`);", "}", "");
  }
  writeFileSync(join(contentLib, "generated.ts"), lines.join("\n"));
}

async function check() {
  const { Pack, loadBook, loadLearn, loadWords } =
    await import("@gutentype/content");
  const { loadCorpus, meetsLearnFloor } = await import("@gutentype/lesson");
  const es = Pack.ALL.get("es");
  const fail = (msg: string) => {
    console.error(`FAIL ${msg}`);
    process.exit(1);
  };
  if (es.id !== "es") fail("the es pack is not registered");
  if (es.info.language !== "es") fail("language");
  const book = await loadBook(es, "juan");
  if (book.chapters[0][0] !== juan[0][0]) fail("Juan 1:1 text");
  const words = await loadWords(es);
  if (!words.some(([w]) => w === "verbo")) fail("word list");
  const learn = await loadLearn(es);
  if (learn.fragments.length === 0) fail("learn.json fragments");
  const corpus = await loadCorpus(es);
  console.log(
    `PASS es pack loads: ${Pack.ALL.map(String).join(", ")}; Juan 1:1 "${book.chapters[0][0]}"; ` +
      `${words.length} words; ${learn.fragments.length} fragments; Learn corpus: ${meetsLearnFloor(corpus) ? "yes" : "no (Read only, Learn stays on BSB)"}`,
  );
}

if (import.meta.main) {
  switch (process.argv[2]) {
    case "add":
      addDummyPack();
      writeGenerated();
      break;
    case "check":
      await check();
      break;
    default:
      console.error("usage: pack-isolation.ts add|check");
      process.exit(2);
  }
}
